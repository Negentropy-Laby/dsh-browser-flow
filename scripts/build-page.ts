/** Compile fixed DOM functions before serializing their JavaScript bodies. */
import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const root=join(dirname(fileURLToPath(import.meta.url)),'..')
const entries={PAGE_FILE_SOURCE:['file','materializeFile'],PAGE_RUNTIME_SOURCE:['runtime','createRuntime'],PAGE_IDENTITY_SOURCE:['operations','identity'],PAGE_OBSERVE_SOURCE:['operations','observe'],PAGE_FIND_SOURCE:['operations','find'],PAGE_ACTION_SOURCE:['operations','action'],PAGE_WAIT_SOURCE:['operations','wait'],PAGE_POLICY_SOURCE:['policy','policy'],PASSIVE_IMPORT_SOURCE:['import','passiveImport']} as const

/** @param file - tsc-emitted module. @param symbol - fixed function name. @returns Self-contained JavaScript function text. */
export function compiledFunction(file:string,symbol:string): string {
  const text=readFileSync(file,'utf8')
  const parsed=ts.createSourceFile(file,text,ts.ScriptTarget.ES2022,true,ts.ScriptKind.JS)
  if(parsed.statements.some(ts.isImportDeclaration))throw new Error('Page programs cannot depend on runtime imports')
  const declaration=parsed.statements.find((statement): statement is ts.FunctionDeclaration=>ts.isFunctionDeclaration(statement)&&statement.name?.text===symbol)
  if(!declaration)throw new Error('Missing fixed page program: '+symbol)
  const source=declaration.getText(parsed).replace(/^export\s+/,'')
  if(/\b__(?:rewriteRelativeImportExtension|awaiter|generator|assign|spreadArray|read|values|name|toESM|commonJS)\b/.test(source))throw new Error('Fixed programs cannot capture compiler helpers')
  return source
}

/** @returns Sources compiled by tsc, never functions transformed by tsx. */
export function buildPagePrograms(): Record<keyof typeof entries,string> {
  rmSync(join(root,'.cache','page-js'),{recursive:true,force:true})
  rmSync(join(root,'.cache','page.tsbuildinfo'),{force:true})
  const compiled=spawnSync(process.execPath,[join(root,'node_modules','typescript','bin','tsc'),'-p',join(root,'tsconfig.page.json')],{cwd:root,stdio:'inherit'})
  if(compiled.status!==0)throw new Error('Fixed page program compilation failed')
  const sources={} as Record<keyof typeof entries,string>
  for(const name of Object.keys(entries) as (keyof typeof entries)[]){
    const [file,symbol]=entries[name]
    sources[name]=compiledFunction(join(root,'.cache','page-js',file+'.js'),symbol)
    if(/\b(?:process|require|Buffer)\b|node:/.test(sources[name]))throw new Error('Page programs cannot use Node capabilities')
    if(name!=='PASSIVE_IMPORT_SOURCE'&&/XMLHttpRequest/.test(sources[name]))throw new Error('XHR is confined to passive import observation')
    if(/document\.cookie|localStorage|sessionStorage|indexedDB/.test(sources[name]))throw new Error('Page programs cannot read credentials or storage')
  }
  const hash=createHash('sha256')
  for(const file of readdirSync(join(root,'src','page')).filter(file=>file.endsWith('.ts')).sort())hash.update(file).update(readFileSync(join(root,'src','page',file)))
  mkdirSync(join(root,'lib'),{recursive:true})
  const module='// Generated by scripts/build-page.ts.\n'+Object.entries(sources).map(([name,value])=>'export const '+name+' = '+JSON.stringify(value)+';').join('\n')+'\n'
  writeFileSync(join(root,'lib','page-programs.js'),module)
  copyFileSync(join(root,'src','page','program-sources.d.ts'),join(root,'lib','page-programs.d.ts'))
  writeFileSync(join(root,'.cache','page-programs.json'),JSON.stringify({sourceSha256:hash.digest('hex'),sha256:createHash('sha256').update(module).digest('hex'),programs:Object.keys(sources)},null,2)+'\n')
  return sources
}
if(process.argv[1]!==undefined&&fileURLToPath(import.meta.url)===process.argv[1]){
  buildPagePrograms()
  process.stdout.write('browser-flow: fixed TypeScript page programs compiled\n')
}
